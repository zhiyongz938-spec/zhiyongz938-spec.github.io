const TAROT_ALL = (() => {
  const list = [];
  TAROT_MAJOR.forEach(n => list.push({ name: n, type: '大阿卡纳' }));
  Object.keys(TAROT_SUITS).forEach(s => {
    TAROT_SUITS[s].forEach(n => list.push({ name: n, type: '小阿卡纳·' + s }));
  });
  return list;
})();

function drawTarot(n) {
  const deck = [...TAROT_ALL];
  // Fisher-Yates 洗牌
  for (let i = deck.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }
  return deck.slice(0, n).map(card => ({
    ...card,
    upright: Math.random() >= 0.5,
  }));
}
